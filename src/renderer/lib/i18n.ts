let _serverLocale: string | undefined

export function setServerLocale(locale: string | undefined) {
  _serverLocale = locale
}

export function detectLanguage(): Language {
  const candidates = [
    typeof navigator !== 'undefined' ? navigator.language : '',
    ...(typeof navigator !== 'undefined' && Array.isArray(navigator.languages) ? navigator.languages : []),
    _serverLocale ?? ''
  ]
  for (const raw of candidates) {
    if (!raw) continue
    const tag = String(raw)
    if (/^zh\b/i.test(tag)) {
      if (/Hant/i.test(tag) || /-(TW|HK|MO)\b/i.test(tag)) return 'zh-TW'
      return 'zh-CN'
    }
    if (/^ja\b/i.test(tag)) return 'ja'
    if (/^ko\b/i.test(tag)) return 'ko'
    if (/^fr\b/i.test(tag)) return 'fr'
    if (/^es\b/i.test(tag)) return 'es'
    if (/^en\b/i.test(tag)) return 'en'
  }
  return 'en'
}

export function resolveLanguage(pref: LanguagePref): Language {
  return pref === 'auto' ? detectLanguage() : pref
}

